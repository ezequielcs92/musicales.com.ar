def logo_body(dark=False,mono=False):
    ink=LIGHT if dark else INK;accent=ink if mono else PINK if dark else ACCENT
    return f'<path fill="{accent}" d="{markpath}"/><path fill="{ink}" d="{wordpath}"/>'
def mark_body(dark=False,mono=False):
    ink=LIGHT if dark else INK;accent=ink if mono else PINK if dark else ACCENT
    return f'<path fill="{accent}" d="{markpath}"/>'
def place_logo(x,y,width,dark=False):return f'<g transform="translate({x} {y}) scale({width/W})">{logo_body(dark)}</g>'
def place_mark(x,y,size,dark=False):return f'<g transform="translate({x} {y}) scale({size/100})">{mark_body(dark)}</g>'
