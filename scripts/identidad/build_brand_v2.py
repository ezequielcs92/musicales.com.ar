INK,PAPER,LIGHT,ACCENT,PINK='#171320','#F4F3F6','#F0EDF4','#9E1B3C','#E36285'

def outline(text,x,y,size=100,weight=700,spacing=0,font=None):
    font=font or fonts[weight];glyphs=font.getGlyphSet();cmap=font.getBestCmap();scale=size/font['head'].unitsPerEm
    pen=SVGPathPen(glyphs);cursor=x
    for i,char in enumerate(text):
        glyph=glyphs[cmap[ord(char)]];glyph.draw(TransformPen(pen,(scale,0,0,-scale,cursor,y)))
        cursor+=glyph.width*scale+(spacing if i<len(text)-1 else 0)
    return pen.getCommands(),cursor

def path(text,x,y,size=100,weight=700,color=INK):
    d,_=outline(text,x,y,size,weight);return f'<path fill="{color}" d="{d}"/>'
def rect(x,y,w,h,color):return f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" fill="{color}"/>'
def svg(body,w,h,label='Musicales.com.ar'):return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:g} {h:g}" role="img" aria-label="{label}">{body}</svg>'

